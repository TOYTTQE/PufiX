		if not arg:
			print("\033[1mqlist — Quick List:\033[0m")
			print("  \033[36mqlist countries\033[0m — страны")
			print("  \033[36mqlist all\033[0m       — всё сразу")
			print("")
			print("\033[1mЯзыки:\033[0m  ru (по умолчанию) | en | both")
			return

