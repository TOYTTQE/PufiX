			for section, items in DATA.items():
				print("\n\033[1m── " + section + " ──\033[0m")
				for item in items:
					symbol, code, name_ru, name_en = item
					if lang == "en":
						print("  \033[33m" + symbol.ljust(5) + "\033[0m" + code.ljust(12) + name_en)
					elif lang == "both":
						print("  \033[33m" + symbol.ljust(5) + "\033[0m" + code.ljust(12) + name_ru + " / " + name_en)
					else:
						print("  \033[33m" + symbol.ljust(5) + "\033[0m" + code.ljust(12) + name_ru)
			return

