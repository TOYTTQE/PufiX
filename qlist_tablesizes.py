def handle(command):
	if not command.startswith("qlist_tablesizes"):
		return

	parts = command.split(maxsplit=2)
	arg = parts[1] if len(parts) > 1 else ""
	lang = parts[2] if len(parts) > 2 else "ru"

	if not arg:
		print("\033[1mqlist_tablesizes — Size Conversions:\033[0m")
		for section in TABLES:
			print("  \033[36mqlist_tablesizes " + section + "\033[0m")
		print("  \033[36mqlist_tablesizes all\033[0m — всё сразу")
		print("")
		print("\033[1mЯзыки:\033[0m  ru (по умолчанию) | en | both")
		return

	def print_row(item):
		a_ru, b_ru, a_en, b_en = item
		if lang == "en":
			print("  \033[33m" + a_en.ljust(18) + "\033[0m= " + b_en)
		elif lang == "both":
			print("  \033[33m" + a_ru.ljust(18) + "\033[0m= " + b_ru + "  \033[90m|\033[0m  \033[33m" + a_en.ljust(18) + "\033[0m= " + b_en)
		else:
			print("  \033[33m" + a_ru.ljust(18) + "\033[0m= " + b_ru)

	if arg == "all":
		for section, items in TABLES.items():
			print("\n\033[1m── " + section + " ──\033[0m")
			for item in items:
				print_row(item)
		return

	if arg in TABLES:
		print("\033[1m── " + arg + " ──\033[0m")
		for item in TABLES[arg]:
			print_row(item)
	else:
		print("\033[31m\033[1mError: UnknownTable <" + arg + ">\033[0m")
